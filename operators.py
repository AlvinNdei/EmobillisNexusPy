#Arithmetic operators-simple calculations

x=10
y=5

print(x+y)
print(x-y)
print(y-x)
print(x*y)
print(x**y)
print(x%y)
print(x/y)

#comparison operators-return a boolean
num1=50
num2=67

print(num1<num2)
print(num1>num2)
print(num1>=num2)
print(num1<=num2)
print(num1==num2)
print(num1!=num2)

#assignment operators-Assign/store values in variables
number=10
print(number)

#operator precedence-order in which operations get executed
number -=2
number +=2
print(number)

#Logical operators- and, or, not
print(100==30 and 60<200)#returns true if all conditions are true
print(100==30 or 60<200)#returns true if either(any) of the conditions are true
print(not(100==30 or 60<200))#negates the result of a given condition